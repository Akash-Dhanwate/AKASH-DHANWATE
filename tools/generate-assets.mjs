function frozen(source, removeMotionGroups = false) {
  if (removeMotionGroups) source = source.replace(/<g class="motion">[\s\S]*?<\/g>/g, '');
  return source.replace(/<animate(?:Motion|Transform)?\b[^>]*\/>/g, '');
}
for (const mobile of [false, true]) {
  const name = mobile ? 'hero-mobile' : 'hero';
  const source = hero(mobile);
  fs.writeFileSync(path.join(out, `${name}.svg`), source);
  fs.writeFileSync(path.join(out, `${name}-static.svg`), frozen(source, true));
}

function focus(mobile = false) {
  const w = mobile ? 600 : 1200, h = mobile ? 108 : 80;
  const x = mobile ? 30 : 245, y = mobile ? 77 : 50, size = mobile ? 25 : 29;
  const lines = ['AI & machine learning', 'Data, models & decisions', 'Full-stack systems'];
  const steps = Array.from({ length: 26 }, (_, i) => Math.round(i * (w - x - 25) / 25));
  const values = [...steps, w - x - 25, 0].join(';');
  const times = [...steps.map((_, i) => (i * .42 / 25).toFixed(4)), '.92', '1'].join(';');
  let body = `<rect width="${w}" height="${h}" fill="${C.bg}"/>${mono('CURRENT EXPLORATIONS', mobile ? 30 : 56, mobile ? 29 : 46, mobile ? 16 : 13, C.cyan)}`;
  body += `<g class="motion" clip-path="url(#type)">`;
  lines.forEach((line, i) => {
    body += `<g opacity="${i === 0 ? 1 : 0}">${lettering(line, x, y, size)}<animate attributeName="opacity" calcMode="discrete" values="${i === 0 ? '1;0;0;1' : i === 1 ? '0;1;0;0' : '0;0;1;0'}" keyTimes="0;.333333;.666667;1" dur="18s" repeatCount="indefinite"/></g>`;
  });
  body += `</g><g class="reduced">${lettering(lines[0], x, y, size)}</g>`;
  const defs = `<clipPath id="type"><rect x="${x}" y="0" width="${w - x - 25}" height="${h}"><animate attributeName="width" calcMode="discrete" values="${values}" keyTimes="${times}" dur="6s" repeatCount="indefinite"/></rect></clipPath>`;
  return svg(w, h, 'Current explorations: AI and machine learning; data, models and decisions; full-stack systems.', 'One locally hosted typing sequence. Each message types slowly, holds for reading, and changes after six seconds. Reduced-motion mode keeps the first message visible.', body, defs);
}
for (const mobile of [false, true]) {
  const name = mobile ? 'focus-mobile' : 'focus';
  const source = focus(mobile);
  fs.writeFileSync(path.join(out, `${name}.svg`), source);
  fs.writeFileSync(path.join(out, `${name}-static.svg`), frozen(source));
}

