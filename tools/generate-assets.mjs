import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'assets');
fs.mkdirSync(out, { recursive: true });
const fontPath = path.join(root, 'node_modules/@fontsource/space-grotesk/files/space-grotesk-latin-700-normal.woff');
const font = opentype.loadSync(fontPath);
const esc = s => String(s).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
const C = { bg: '#080B14', panel: '#101524', line: '#27324B', white: '#F2F4FC', muted: '#A8B3CC', violet: '#AE94FF', cyan: '#79E8E0' };

function lettering(value, x, y, size, fill = C.white) {
  return `<path fill="${fill}" d="${font.getPath(value, x, y, size, { kerning: true }).toPathData(2)}"/>`;
}
function mono(value, x, y, size = 15, fill = C.muted, extra = '') {
  return `<text x="${x}" y="${y}" fill="${fill}" font-family="ui-monospace,SFMono-Regular,Consolas,monospace" font-size="${size}" ${extra}>${esc(value)}</text>`;
}
function svg(w, h, title, description, body, defs = '') {
  return `<!-- Generated by tools/generate-assets.mjs. Display paths: Space Grotesk, SIL OFL 1.1. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-labelledby="title desc">
<title id="title">${esc(title)}</title><desc id="desc">${esc(description)}</desc>
<defs>${defs}</defs>
<style>.reduced{display:none}@media(prefers-reduced-motion:reduce){.motion{display:none}.reduced{display:inline}}</style>
${body}
</svg>\n`;
}
const gradients = `
<linearGradient id="signal" x1="0" y1="0" x2="1" y2="1"><stop stop-color="${C.violet}"/><stop offset="1" stop-color="${C.cyan}"/></linearGradient>
<radialGradient id="atmosphere"><stop stop-color="#7D52DC" stop-opacity=".2"/><stop offset="1" stop-color="#080B14" stop-opacity="0"/></radialGradient>
<pattern id="grid" width="40" height="40" patternUnits="userSpaceOnUse"><path d="M40 0H0V40" fill="none" stroke="${C.line}" stroke-opacity=".35" stroke-width=".6"/></pattern>
<filter id="glow" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="3"/></filter>`;

function monogram(cx, cy, scale = 1) {
  const routes = ['M-175-138H-112L-76-102','M195-143H139L107-101','M-185 126H-121L-90 95','M192 132H141L105 94','M-220-22H-153L-114 18','M222 12H188'];
  let lattice = '';
  for (let row = -9; row <= 9; row++) {
    for (let col = -15; col <= 15; col++) {
      const x = col * 11, y = row * 11;
      const ax = -61 + y * 0.42;
      const aStroke = Math.abs(x - ax) < 9 || Math.abs(x - (-61 - y * 0.42)) < 9 || (y > 19 && y < 32 && x > -110 && x < -10);
      const dStroke = (x > 44 && x < 57) || ((Math.abs(y) > 78) && x > 48 && x < 99) || (Math.abs(Math.hypot((x - 72) * 1.12, y) - 92) < 8 && x > 79);
      if (aStroke || dStroke) lattice += `<rect x="${x}" y="${y}" width="3" height="3" fill="${(row + col) % 4 === 0 ? C.cyan : C.violet}" opacity=".75"/>`;
    }
  }
  const ad = 'M-139 91L-62-91L15 91M-113 29H-11M48-91H85C211-91 211 91 85 91H48Z';
  return `<g transform="translate(${cx} ${cy}) scale(${scale})">
<circle r="206" fill="url(#atmosphere)"/>
<g fill="none" stroke="${C.line}" stroke-width="1"><circle r="170" stroke-dasharray="2 10"/><path d="M-205-172H-165M-205-172V-132M205-172H165M205-172V-132M-205 172H-165M-205 172V132M205 172H165M205 172V132"/>
${routes.map(d => `<path d="${d}"/>`).join('')}</g>
<path d="${ad}" fill="none" stroke="url(#signal)" stroke-width="19" opacity=".17" filter="url(#glow)"/>
<path d="${ad}" fill="none" stroke="url(#signal)" stroke-width="1.2" opacity=".65"/>
${lattice}
<path d="${ad}" fill="none" stroke="${C.cyan}" stroke-width="1.8" pathLength="100" stroke-dasharray="100" stroke-dashoffset="0" class="motion"><animate attributeName="stroke-dashoffset" values="100;0" dur="3s" repeatCount="1"/></path>
<g fill="${C.cyan}"><circle cx="-175" cy="-138" r="2.5"/><circle cx="195" cy="-143" r="2.5"/><circle cx="-185" cy="126" r="2.5"/><circle cx="192" cy="132" r="2.5"/></g>
<g class="motion">${routes.slice(0, 4).map((d, i) => `<circle r="2.8" fill="${i % 2 ? C.violet : C.cyan}"><animateMotion path="${d}" dur="${8 + i}s" begin="${i * 1.2}s" repeatCount="indefinite"/><animate attributeName="opacity" values="0;1;1;0" keyTimes="0;.2;.7;1" dur="${8 + i}s" repeatCount="indefinite"/></circle>`).join('')}</g>
</g>`;
}

